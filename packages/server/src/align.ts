  for (let i = 0; i < items.length; i++) {
    if (usedItem.has(i)) continue;
    // ⚠️ 只补「完全没判出季」的条目。
    //    试过也覆盖 `itemStrength === 'year'`（年份是最弱的线索，47001 就是被年份带错的）：
    //    实测 6149（净 +56），但 **丢失 15 / 换集 17**，其中 68704 的两条
    //    「第1話 / S-第1話」原本靠集号锚得**完全正确**，被组判据搬走后反而配不上。
    //    ⇒ 数量涨了、正确性掉了 = 排列抖动，⛔ 不采纳。要动年份覆盖必须先能解释这 15 条。
    if (itemSeason[i] >= 0) continue;
    if (groupSeasonOf[i] >= 0) {
      itemSeason[i] = groupSeasonOf[i];
      itemStrength[i] = 'hint';
    }
  }

