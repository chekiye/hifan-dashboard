/* ═══════════════════════════════════════════════════════════════════════
   逐集对齐 —— 把「TMDB 的分季分集」和「源站的每条视频」摆成一张表

   ⭐ 动机（蛙哥 2026-10-21）：
     「tmdb 上不是已经有完整的分季分集吗，我们只要把 hanime 和 mteam 对应的数据
       放它下面，这样不是一眼就看出来对不对，有没有缺少吗」
     —— 对。原来的溯源面板是「源站一堆 + TMDB 一堆」各摊各的，
        要靠人脑去对。摆成一张表，缺哪一集、源站是不是多出别的作品，一眼可见。

   ⚠️ 本模块**只做呈现与统计**，不参与任何匹配判定，也不写库。
   ═══════════════════════════════════════════════════════════════════════ */

/** 一条可参与对齐的源条目 */
export interface AlignItem {
  kind: 'hanime' | 'mteam';
  /** hanime：vid；mteam：src_key（番号） */
  id: string;
  title: string;
  /** 日文原名（hanime 才有，来自 entry_detail[].title_ja） */
  titleJa?: string | null;
  /**
   * 🔴 **播放页**完整标题（2026-10-26 §67 补抓，hanime 才有）。
   *
   * 蛙哥原话：「hanime 的页面标题和播放页标题不一样的 …… 这问题我感觉很多」。
   *   `title` 是**列表页/入库时**拿到的短标题，`title_page` 是打开播放页后
   *   浏览器 `<title>` 里的完整标题 —— 才是源站对该视频的正式叫法。
   *   看板显示必须用这个，否则标题被截断、看不出是第几巻。
   *
   * ⛔ **绝不能直接把 `title` 换成本字段**（2026-10-26 实测 A/B）：
   *   `title` 是 `alignVol()` 的输入（卷号从标题末尾的 N 提取）。换成日文
   *   播放页标题后卷号形态不符 ⇒ 卷号档整档失效 ⇒ 全库
   *   **withSource −26 / hung −60 / extra +64，14 部落位崩**。
   *   ⇒ `title` 保持原样喂对齐；本字段**只用于显示**（前端 `titlePage || title`）。
   */
  titlePage?: string | null;
  /**
   * 源站播放清单编号（hanime 才有，来自 entry_detail[].playlist_id）。
   *
   * ⭐ 2026-10-21 入库：这是源站**自己的分组编号** —— 同一个清单里的视频
   *   就是源站认为的同一部作品。核对时两集清单号相同 = 源站确实归在一部里；
   *   不同 = 源站都没把它们算作同一部，这时才该怀疑绑定是不是错了。
   * ⚠️ 清单 ≠ 作品的硬边界：实测有 38 个清单装了多部不同作品（多语种合集），
   *   所以它只能当**辅助证据**，不能当分组依据自动合并。
   */
  playlistId?: string | null;
  year?: number | null;
  /** 所属源记录（同一行可能有多条） */
  srcKey: string;
  /** 源站自己的卷号（标题结尾的 N） */
  vol: number;
  /**
   * ⭐ §87（2026-10-30）：这一条源条目在 `source_link` 表里的下载链接状态。
   *
   * 蛙哥原话：「我想要看到的效果，哪里缺集了，hanime 更新了没，
   *   对应下载链接抓到了吗」—— 所以链接必须和源条目**长在一起**，
   *   一个格子上挂了两条源（合并发售）时两条各自的链接也要分开看。
   *
   * 🔴 由 `BoardApi.detail()` 用 matcher 的 `readEpisodeLinks()` 按 vid 挂上
   *    （⛔ align 自己查库 —— 它是纯函数模块，碰 DB 就没法单测了）。
   * ⛔ 只带「判断需不需要重抓」的字段，完整 URL 走 `/api/dl/link/:vid` 单独取。
   * `null` = 源站有这一条、但链接表里没有（真缺口）。
   */
  link?: {
    quality: number | null;
    isM3u8: boolean;
    expiresAt: number | null;
    srcKind: string | null;
    rateLimit: number | null;
    /**
     * ⭐ §116：源侧这一集的**真实字节数**（HEAD 拿的 content-length）。
     * 🔴 与上面几个字段的寿命完全不同：链接 11~35 小时就过期，**体积永久有效**
     *    ⇒ 过期后 `quality/expiresAt` 已经没用了，但 `size` 照样该显示。
     * ⛔ 前端不许拿 0 或估算值顶 null。
     */
    size?: number | null;
  } | null;
  /**
   * ⭐ 2026-10-23：**人工指定的集号**（终极优先级）。
   *
   * 场景：TMDB 一个词条收了**多部子作品**（合集），子作品的源站卷号
   *   与 TMDB 的全局集号**天然不对应** —— 任何启发式都判不出来，因为
   *   「episode1」在它自己那部里确实是第 1 集。实例 #258103
   *   シークレットアニマシリーズ：`MAMA Vol.1/2`（飛龍乱）= E1/E2，
   *   `episode1/2`（2×1 FOUR PLAY）= E4/E5。marker 档会把 episode1
   *   读成第 1 集 ⇒ 抢走 E1/E2、飛龍乱 反被挤进 extra。
   *
   * ⇒ 只能由**人工钉死**：board.ts 从 `data/align_ep_override.json`
   *   按源条目 id 注入。⛔ 不要试图用相似度/数字规则自动推这类。
   */
  epOverride?: number | null;
  /**
   * ⭐ 2026-10-28（§79-z-3）：**人工指定「这一条源同时覆盖多集」**。
   *
   * 场景：源站的条目是**合并发售**的 —— 一个视频里装了两集。
   *   实例 #100907 幻梦馆：`真章・幻夢館 Epilogue 第1+2話`
   *   「第3+4話」两集一个种子 ⇒ 这**一条源**要同时挂在 S2E1 和 S2E2 上，
   *   而 `epOverride` 只能钉一个集号 ⇒ 另一集会永远显示「缺源」。
   *
   * ⚠️ 与 `epOverride` 并存：解析到数组时两个都写（epOverride 取首项，
   *   供只读单值的旧路径使用），对齐档优先走 `epOverrideAll`。
   * ⚠️ 只在显式写入时生效；为空时整条对齐逻辑**完全不变**（严格 no-op）。
   */
  epOverrideAll?: number[] | null;
  /**
   * ⭐ 2026-10-23：**人工指定的季号**（与 epOverride 配对使用）。
   *
   * 场景：源的「卷号」跨季连续编号（第4/5/6巻 其实是第二季的第1/2/3集），
   *   或是 mteam 侧 `year` 记的是 DVD 售卖年（1998）⇒ 年份判季会把它拉去
   *   错误的一季。这时光靠 epOverride（只在本季内生效）救不回来 ——
   *   条目本身已经站错季了。
   *
   * ⇒ 人工同时钉「哪一季 + 季内第几集」。实例 #126810 誘惑 COUNT DOWN：
   *   hanime「倒數計時 4/5/6」（year 1997）与 mteam「第4/5/6巻 鏡AKIRA」
   *   都属 S2 `镜之篇`，但卷号 4/5/6 在 S2（只有 3 集）里无处可落。
   *
   * ⚠️ 只有显式写入才生效；为空时整条季归属逻辑**完全不变**（严格 no-op）。
   */
  epSeason?: number | null;
}

/** 对齐结果里的一行 = TMDB 的一集 */
export interface AlignRow {
  season: number;
  episode: number;
  epName: string | null;
  airDate: string | null;
  hanime: AlignItem[];
mteam: AlignItem[];
  /** 配对依据：
   *   named  = **源标题引号里的集名**逐字对上 TMDB 集名（确定，最硬 —— 2026-10-23）
   *   strong = 集名/分集名逐字命中（确定）
   *   marker = 源标题自带【第NN話】且等于集号（确定）
   *   season = 季名+数量对上的季内按序对应（较可信）
   *   vol    = 卷号=集号（推定）
   *   year   = 同年（推定）
   *   order  = 无依据（未确定）
   *   pack   = **整部包**：源站只有一条、不标任何集号，一个种子覆盖整部（2026-10-22）
   *   override = **人工指定**（合集里子作品卷号 ≠ TMDB 全局集号，见 AlignItem.epOverride） */
  how: 'named' | 'strong' | 'marker' | 'season' | 'vol' | 'year' | 'order' | 'ja' | 'pack' | 'override';
}

/** 没对上任何一集的源条目（可能绑错作品、也可能是 TMDB 没收） */
export interface AlignExtra {
  kind: 'hanime' | 'mteam';
  id: string;
  title: string;
  /** 日文原名（hanime 才有） */
  titleJa?: string | null;
  /** 源站播放清单编号（hanime 才有）—— 多出来的条目属于哪个清单 */
  playlistId?: string | null;
  year: number | null;
  srcKey: string;
}

export interface AlignResult {
  rows: AlignRow[];
  extra: AlignExtra[];
  summary: {
    tmdbEps: number;
    withSource: number;
    missing: number;
    sourceItems: number;
    extra: number;
  };
}

